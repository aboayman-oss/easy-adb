export function classifyPackage(pkg: string, isSystem: boolean): KnownPackage {
  const known = DB.get(pkg)
  if (known) return known
  if (!isSystem) return { name: prettifyPackageName(pkg), safety: 'safe', description: 'An app you (or your phone’s seller) installed.' }
  if (CORE_PATTERNS.some((re) => re.test(pkg))) {
    return { name: prettifyPackageName(pkg), safety: 'core', description: 'Part of Android itself.' }
  }
  return {
    name: prettifyPackageName(pkg),
    safety: 'caution',
    description: 'A pre-installed system app. Remove only if you know what it does.'
  }
}

const NOISE = new Set([
  'com', 'org', 'net', 'android', 'app', 'apps', 'sec', 'samsung', 'google', 'miui', 'xiaomi', 'oppo', 'coloros',
  'oplus', 'heytap', 'oneplus', 'motorola', 'huawei', 'mi', 'global', 'client', 'mobile', 'service', 'services',
  'provider', 'providers', 'lite', 'android_', 'in', 'co', 'io', 'de', 'uk'
])

const ACRONYMS = new Set(['tv', 'ar', 'vr', 'ai', 'id', 'os', 'ui', 'fm', 'qr', 'hd', 'sd', 'pc', 'gps', 'nfc', 'sms', 'mms', 'vpn', 'ims', 'sim', 'usb'])

/** Turn a package id into a readable fallback name, e.g. com.foo.photo_editor → "Photo Editor". */
export function prettifyPackageName(pkg: string): string {
  const parts = pkg.split('.').filter(Boolean)
  let pick = ''
  for (let i = parts.length - 1; i >= 0; i--) {
    if (!NOISE.has(parts[i].toLowerCase())) {
      pick = parts[i]
      break
    }
  }
  if (!pick) pick = parts[parts.length - 1] ?? pkg
  const words = pick
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/[_-]+/g, ' ')
    .replace(/(\D)(\d)/g, '$1 $2')
    .trim()
    .split(/\s+/)
  return words.map((w) => (ACRONYMS.has(w.toLowerCase()) ? w.toUpperCase() : w[0].toUpperCase() + w.slice(1))).join(' ')
}
